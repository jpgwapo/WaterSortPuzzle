    static var allLevels: [PuzzleLevel] { levels }
    static var totalLevelCount: Int { levels.count }

    static func level(_ number: Int) -> PuzzleLevel? {
        levels.first { $0.id == number }
    }

    static func level(number: Int) -> PuzzleLevel? {
        level(number)
    }

    private static var e: Tube { Tube() }

    private static func t(_ colors: LiquidColor...) -> Tube {
        Tube(layers: colors)
    }

    private static func level(
        _ id: Int,
        _ title: String,
        _ difficulty: PuzzleLevel.Difficulty,
        _ tubes: [Tube]
    ) -> PuzzleLevel {
        PuzzleLevel(id: id, title: title, difficulty: difficulty, tubes: tubes)
    }
